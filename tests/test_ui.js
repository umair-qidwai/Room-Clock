// Optional frontend checks: node tests/test_ui.js
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/index.html', 'utf8');
const script = source.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script); // Parse the entire frontend without touching real devices.
const fn = script.match(/function autoKind\(\)\{[^\n]+/)[0];
const context = {data: {morning_done: false, night_done: false}};
vm.createContext(context);
vm.runInContext(fn, context);
assert.equal(vm.runInContext('autoKind()', context), 'usage');
context.data.shuruq = {state: 'invalid'};
context.data.isha_iqama = {state: 'invalid'};
assert.equal(vm.runInContext('autoKind()', context), 'usage');
context.data.shuruq = {state: new Date(Date.now() - 3600000).toISOString()};
context.data.isha_iqama = {state: new Date(Date.now() + 3600000).toISOString()};
assert.equal(vm.runInContext('autoKind()', context), 'usage');
context.data.morning_done = true;
assert.equal(vm.runInContext('autoKind()', context), 'usage');
context.data.isha_iqama = {state: new Date(Date.now() - 1000).toISOString()};
assert.equal(vm.runInContext('autoKind()', context), 'usage');
context.data.night_done = true;
assert.equal(vm.runInContext('autoKind()', context), 'usage');
const noonFn = script.match(/function shouldAutoRunMorningAtNoon\([^\n]+/)[0];
vm.runInContext(script.match(/function clockZone\(\)\{[^\n]+/)[0], context);
vm.runInContext(script.match(/function timeParts\([^\n]+/)[0], context);
vm.runInContext(noonFn, context);
context.data.morning_done = false;
context.data.morning_automation_configured = true;
assert.equal(vm.runInContext("shouldAutoRunMorningAtNoon(new Date('2026-10-06T11:59:59'))", context), false);
assert.equal(vm.runInContext("shouldAutoRunMorningAtNoon(new Date('2026-10-06T12:00:00'))", context), true);
context.data.morning_done = true;
assert.equal(vm.runInContext("shouldAutoRunMorningAtNoon(new Date('2026-10-06T13:00:00'))", context), false);
assert.ok(!script.includes('boys_room'));
assert.ok(script.includes('/api/room/toggle'));
const widgetsFn = script.match(/function widgetList\(\)\{[^\n]+/)[0];
vm.runInContext(widgetsFn, context);
assert.deepEqual(Array.from(vm.runInContext('widgetList()', context)), ['usage', 'summary']);
context.serverNow = () => new Date('2026-10-11T13:30:00');
context.data.weather_hourly = Array.from({length: 15}, (_, i) => ({
  datetime: new Date(2026, 9, 11, 12+i).toISOString(), temperature: 70-i
}));
const hoursFn = script.match(/function hourlyItems\(\)\{[^\n]+/)[0];
vm.runInContext(script.match(/function localDateKey\([^\n]+/)[0], context);
vm.runInContext(hoursFn, context);
context.innerWidth = 800; context.innerHeight = 360;
const futureHours = Array.from(vm.runInContext('hourlyItems()', context));
assert.equal(futureHours.length, 10, 'Include every remaining hour today, not just the first screen');
assert.equal(new Date(futureHours[0].datetime).getHours(), 14);
assert.equal(new Date(futureHours.at(-1).datetime).getHours(), 23);
context.data.weather_hourly.reverse();
assert.equal(new Date(vm.runInContext('hourlyItems()[0].datetime', context)).getHours(), 14);
context.serverNow = () => new Date('2026-10-11T23:30:00');
assert.equal(vm.runInContext('hourlyItems().length', context), 0, 'Do not include tomorrow or elapsed hours');
console.log('Frontend parsing and widget selection: PASS');
